我撤了那道命令，给补报留了一次期限，同时把补报与查明的舞弊分开。没人因此突然变得诚实，至少有几处终于愿意告诉我：“这个数，我们也不知道。”如果你的模块只会提示风险、不会提示纠错的代价，记得让它重写。一个人承认错了就会掉脑袋时，它提醒再多次也没用。

