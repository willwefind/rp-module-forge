一、不要急着改革。
我刚醒来的前三天，最大的错误是相信“皇帝”两个字意味着我已经拥有这个国家。其实我拥有的首先只是一个所有人都需要表演给我看的位置。桌上的折子工整得像同一个人写的，我起初以为这是规矩。后来才知道，坏消息到我这里之前，已经有人替它换好了衣服。

